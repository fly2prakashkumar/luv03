export const getStoredProducts = () => {
  if (typeof window === "undefined") return initialProducts;
  try {
    const stored = localStorage.getItem("luv03-products");
    if (stored) {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed.map((p, idx) => ({
          ...p,
          id: p.id || idx + 1,
          slug:
            p.slug ||
            (p.name
              ? p.name
                  .toLowerCase()
                  .replace(/[^a-z0-9]+/g, "-")
                  .replace(/(^-|-$)+/g, "")
              : "product-" + (p.id || idx + 1)),
          stock: p.stock !== undefined ? Number(p.stock) : 15,
        }));
      }
    }
  } catch (error) {
    console.error("Could not load products from storage:", error);
  }

  try {
    localStorage.setItem("luv03-products", JSON.stringify(initialProducts));
  } catch (e) {}

  return initialProducts;
};

export const saveStoredProducts = (updatedProducts) => {
  if (typeof window === "undefined") return false;
  try {
    localStorage.setItem("luv03-products", JSON.stringify(updatedProducts));
    window.dispatchEvent(new Event("luv03-products-change"));
    return true;
  } catch (error) {
    console.error("Could not save products:", error);
    return false;
  }
};

const products = typeof window !== "undefined" ? getStoredProducts() : initialProducts;

export default products;
